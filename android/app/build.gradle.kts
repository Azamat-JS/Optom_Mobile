// so there's one place to set it. Read at build time: rebuild after changing it.
val mapsApiKey: String = rootProject.file("../.env").takeIf { it.exists() }
    ?.readLines()
    ?.map { it.trim() }
    ?.firstOrNull { it.startsWith("MAPS_API_KEY=") }
    ?.substringAfter("=")
    ?.trim()
    ?: ""

